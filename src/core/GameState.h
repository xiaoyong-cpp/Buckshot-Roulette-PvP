// ============================================================================
// GameState.h - 游戏流程状态枚举（状态模式）
// 独立成头，便于 GameView 等数据结构共享，无需依赖完整 Game 定义。
// ============================================================================
#pragma once

enum class GameState {
    Waiting,    // 等待开始（大厅）
    Reloading,  // 装弹阶段展示（实/空数量公示）
    Aiming,     // 当前玩家行动：可用道具或射击
    ItemSelect, // 正在使用需要指定目标的道具（手铐/肾上腺素）
    Shooting,   // 射击结算（瞬时状态，事件驱动 UI 动画）
    RoundEnd,   // 弹仓已空，等待重新装弹
    GameOver,   // 对局结束
};
