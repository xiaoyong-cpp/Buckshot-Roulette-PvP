// ============================================================================
// Scene.h - 场景接口（设计模式：状态模式在 UI 层的应用）
// 每个界面（主菜单/创建房间/加入房间/大厅/游戏）是一个 Scene，
// 由 SceneManager 负责切换与主循环调度。
// ============================================================================
#pragma once

class Scene {
public:
    virtual ~Scene() = default;
    virtual void OnEnter() {}  // 场景被激活时调用（可多次）
    virtual void Update() = 0;  // 每帧：输入 + 逻辑（不要在此渲染）
    virtual void Draw() = 0;     // 每帧：渲染
};
